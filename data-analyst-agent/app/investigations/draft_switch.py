"""The one switch for whether the Data Analyst may ask the analytics app to generate drafts.

THE RULE. The Data Analyst produces FINDINGS: issues, evidence and priorities. It never creates a fix. Fixes are generated by the
analytics app's Generator from its one recommendation queue and shipped by its one ship run. While this service could also ask
the app to draft (the `generate_draft` MCP call), the same problem on the same page could be drafted twice, once from each side,
outside the queue's limits and ordering.

THE SWITCH. ANALYST_DRAFT_TRIGGER=off turns that off. Anything else (including unset) leaves today's behaviour, so deploying this
file changes nothing until the variable is set. It is read from the process environment, which for this service is the
container's environment: set it where the container is created (the deploy workflow's data-analyst-agent/.env), not on a crontab
line, because the staging cron runs `docker compose exec` into an already-running container.

WHY TWO PLACES. There are two routes to the draft step: scripts/run_nightly_pipeline.py (staging's host crontab) and
app/analysis/run_pass.py (production's in-container scheduler). The check lives where both converge (`run_draft_trigger`) and at
the MCP call itself (`generate_draft`), so no route, present or future, can bypass it.
"""
import logging
import os

logger = logging.getLogger(__name__)


class DraftTriggerDisabled(RuntimeError):
    """Raised by generate_draft() when the switch is off, so a stray caller fails loudly instead of quietly drafting."""


def draft_trigger_enabled() -> bool:
    return os.environ.get("ANALYST_DRAFT_TRIGGER", "on").strip().lower() != "off"


def log_state(where: str) -> None:
    """One line per run saying which way the switch is set, so the logs prove what a deployed container actually received."""
    logger.info("%s: ANALYST_DRAFT_TRIGGER=%s (draft trigger %s)", where,
                os.environ.get("ANALYST_DRAFT_TRIGGER", "<unset>"), "ON" if draft_trigger_enabled() else "OFF: findings only")
