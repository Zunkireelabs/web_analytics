import { pathOf } from './site-scope.js';

// What KIND of page a URL is. Agents written for blogs and service sites treat every page as editable prose; on a marketplace most
// pages are generated from data (categories, listings, seller profiles, search and filter results) and must be handled differently:
// thin or near-duplicate listings are normal, filter URLs need canonical/noindex advice, and a listing is never "edited" by an agent.
//
// Pure of any database or network. Judged from the URL path (plus, optionally, real link structure), never from a per-client constant:
// a site's own layout is declared in url_file_map.pageTypes = [{ match: '^/salon/[^/]+$', type: 'listing' }], which always wins.
// The built-in patterns are a fallback for the common English conventions and are deliberately conservative: an unrecognised path is
// 'content', the existing behaviour, so nothing changes for a site that has no marketplace layout.

export const PAGE_TYPES = Object.freeze(['home', 'blog-post', 'blog-index', 'category', 'listing', 'seller', 'search', 'content']);

// Page types whose body comes from application data, so a content edit to one page is wrong: fix the template or leave it.
export const GENERATED_PAGE_TYPES = Object.freeze(['category', 'listing', 'seller', 'search']);

const FILTER_PARAMS = /^(page|sort|order|filter|q|query|search|s|min|max|price|sortby|view)$/i;

const BUILT_IN = [
  { type: 'search', re: /^\/(search|find|results)(\/|$)/i },
  { type: 'blog-index', re: /^\/(blog|articles|guides|resources|journal|news)\/?$/i },
  { type: 'blog-post', re: /^\/(blog|articles|guides|resources|journal|news)\/[^/]+\/?$/i },
  { type: 'seller', re: /^\/(sellers?|vendors?|providers?|hosts?|shops?|stores?|businesses|professionals?|merchants?)\/[^/]+\/?$/i },
  { type: 'listing', re: /^\/(listings?|products?|items?|salons?|services?|properties|rooms?|jobs|gigs?|offers?|ads?|p)\/[^/]+\/?$/i },
  { type: 'category', re: /^\/(categor(y|ies)|c|browse|collections?|explore|directory)(\/[^/]+)?\/?$/i },
];

function customType(site, path) {
  for (const rule of site?.url_file_map?.pageTypes || []) {
    if (!rule?.match || !PAGE_TYPES.includes(rule.type)) continue;
    try { if (new RegExp(rule.match).test(path)) return rule.type; } catch { /* a bad pattern is skipped, never thrown */ }
  }
  return null;
}

// A URL carrying only sort/pagination/filter parameters is a variant of its base page, not a page of its own.
export function isFacetedUrl(url) {
  let params;
  try { params = [...new URL(url, 'https://x.invalid').searchParams.keys()]; } catch { return false; }
  return params.length > 0 && params.every((k) => FILTER_PARAMS.test(k));
}

// The data-driven built-ins (/services/x, /products/x ...) also match ordinary service and product pages on a non-marketplace site, where
// they ARE editable content. So they apply only once a site has declared a layout (url_file_map.pageTypes); without that declaration
// a site behaves exactly as before. Blog, legal and utility detection is unaffected.
export const declaresPageLayout = (site) => Array.isArray(site?.url_file_map?.pageTypes) && site.url_file_map.pageTypes.length > 0;

// Legal and utility pages are recognised elsewhere (page-content.js) and are 'content' here. This module has no dependency on it on purpose.
export function classifyPageType(site, urlOrPath) {
  const path = pathOf(urlOrPath);
  if (!path) return 'content';
  if (path === '/') return 'home';
  const custom = customType(site, path);
  if (custom) return custom;
  const layout = declaresPageLayout(site);
  for (const { type, re } of BUILT_IN) if ((layout || !GENERATED_PAGE_TYPES.includes(type)) && re.test(path)) return type;
  return 'content';
}

export const isGeneratedPage = (site, urlOrPath, opts) => GENERATED_PAGE_TYPES.includes(classifyPageType(site, urlOrPath, opts));

// Actions that rewrite or add prose on an existing page. Wrong for a page whose body is produced by the application from data.
export const CONTENT_EDIT_ACTIONS = Object.freeze(['faq', 'expand-content', 'qa-content', 'direct-answer', 'comparison-content', 'author-byline', 'internal-links']);

// Why an agent may not edit this page's content, or null when it may. Used as a blocked reason: the finding stays visible for a person.
export function generatedPageBlockReason(site, urlOrPath, actionType) {
  if (!CONTENT_EDIT_ACTIONS.includes(actionType)) return null;
  const type = classifyPageType(site, urlOrPath);
  if (!GENERATED_PAGE_TYPES.includes(type)) return null;
  return `This is a ${type} page whose content is generated by the site's application from data, so a content edit to one page would not stick and could be overwritten on the next build. Fix it in the page template or the data, which needs a developer.`;
}
