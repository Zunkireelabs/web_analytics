export function plainIssue(rawLabel) {
  const label = String(rawLabel || '');
  const rule = ISSUE_RULES.find((r) => r.re.test(label));
  if (rule) return { title: rule.title, why: rule.why, routes: rule.routes, auto: rule.auto || null };
  const clean = label.replace(/[-_]+/g, ' ').replace(/\s+/g, ' ').trim();
  const title = clean ? clean.charAt(0).toUpperCase() + clean.slice(1) : 'Other things to improve';
  return { title, why: 'Fixing this makes your site easier for Google and AI to read and trust.', routes: [], auto: null };
}

