// `report` is a raw baseline_reports row (kpi_snapshot/issues_snapshot/
// narrative_md/generated_at, see store/baseline-reports.js), `site` a raw
// sites row.
export function renderBaselineReportHtml(report, site) {
  const kpi = report.kpi_snapshot || {};
  const issues = report.issues_snapshot || {};
  const dateLabel = new Date(report.generated_at).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: '2-digit' });
  const execAssessmentHtml = marked.parse(extractMarkdownSection(report.narrative_md, 'Where Your Website Stood') || '');

  const pages = [
    coverPage({ siteName: site.name, dateLabel }),
    snapshotPage({ kpi, execAssessmentHtml, siteName: site.name, dateLabel }),
    healthPage({ kpi, auditFindings: issues.auditFindings, siteName: site.name, dateLabel }),
    aiVisibilityPage({ aiVisibility: issues.aiVisibility, siteName: site.name, dateLabel }),
    issuesPage({ openRecommendations: issues.openRecommendations, siteName: site.name, dateLabel }),
    roadmapPage({ siteName: site.name, dateLabel }),
  ].join('\n');

  return `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<title>${escapeHtml(site.name)} — Baseline Report</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=DM+Mono:wght@400;500&family=DM+Sans:opsz,wght@9..40,400;9..40,500;9..40,600;9..40,700&display=swap" rel="stylesheet">
<style>${REPORT_CSS}</style>
</head>
<body>
${pages}
</body>
</html>`;
}

