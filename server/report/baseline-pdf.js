function escapeHtml(s) {
  return String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

const numberFormat = (n) => Number(n ?? 0).toLocaleString('en-US');

// Pulls one `## Heading` section's real text out of the LLM's narrative_md,
// so the Executive Assessment block on page 2 quotes the model's actual
// written words rather than a value re-derived here. Returns '' (never a
// fabricated fallback sentence) when the heading is missing — the caller is
// responsible for handling an empty result honestly.
export function extractMarkdownSection(md, heading) {
  if (!md) return '';
  const re = new RegExp(`^##\\s+${heading.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*$`, 'm');
  const m = re.exec(md);
  if (!m) return '';
  const rest = md.slice(m.index + m[0].length);
  const next = rest.search(/^##\s+/m);
  return (next === -1 ? rest : rest.slice(0, next)).trim();
}

// A short, human title for a recommendation ROW — derived from the real
// `type`/`issue` fields already on the record (never a new fact), the same
// way a person skimming the sentence would summarize it. Falls back to the
// recommendation's own type name, Title Cased, for anything unrecognized —
// never invents a description the data doesn't support.
export function recommendationTitle(item) {
  const issue = String(item.issue || '');
  if (item.type === 'faq') return 'Add FAQ';
  if (item.type === 'landing-page') return 'Generate Landing Page';
  if (item.type === 'schema' || item.type === 'schema-repair') return 'Add Schema Markup';
  if (item.type === 'broken-link-fix') return 'Remove Invalid Citation';
  if (item.type === 'alt-text') return 'Add Image Alt Text';
  if (/comparison|alternatives|best of/i.test(issue)) return 'Add Comparison Content';
  if (/author|byline/i.test(issue)) return 'Add Author/Byline Markup';
  if (/breadcrumb/i.test(issue)) return 'Add Breadcrumbs';
  if (/freshness|last.?updated/i.test(issue)) return 'Add Freshness Signal';
  return String(item.type || 'Recommendation').replace(/[-_]+/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
}

const PRIORITY_ORDER = { high: 0, medium: 1, low: 2 };
const PRIORITY_LABEL = { high: 'HIGH PRIORITY', medium: 'MEDIUM PRIORITY', low: 'LOW PRIORITY' };
const PRIORITY_COLOR = { high: BRAND.red, medium: BRAND.navy, low: BRAND.muted };

const MAX_RECOMMENDATION_ROWS = 8;

// True when the row's supporting sentence would just restate its own title
// verbatim — real data on Admizz's actual report: the record's `issue` field
// for a faq/landing-page/broken-link-fix recommendation IS already the short
// form ("Add FAQ" / "Add FAQ"), so printing both looked like a bug, not a
// title + description. Ignores trailing punctuation/case only — never
// rewrites either string.
export function descriptionRepeatsTitle(title, issue) {
  const norm = (s) => String(s || '').trim().toLowerCase().replace(/[.\s]+$/, '');
  return norm(title) === norm(issue);
}

// Featured list = the highest-priority REPRESENTATIVE of each distinct issue
// type, not the raw top N by priority. Real data on Admizz's audit: of 217
// open items, the first 8 by priority alone were "Add Author/Byline Markup"
// three times and "Add Comparison Content" twice — genuinely the highest-
// priority items, but a report meant to show the SHAPE of what's missing is
// stronger showing 6-8 distinct problems once each than the same headline
// repeated. Every row shown is still a real record for a real page; this
// only decides which of several equivalent real records represents its type.
export function selectFeaturedRecommendations(items, max) {
  const sorted = [...items].sort((a, b) => (PRIORITY_ORDER[a.priority] ?? 9) - (PRIORITY_ORDER[b.priority] ?? 9));
  const seen = new Set();
  const out = [];
  for (const item of sorted) {
    const key = recommendationTitle(item).toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(item);
    if (out.length >= max) break;
  }
  return out;
}

export function scoreStatusWord(score) {
  if (score < 40) return 'NEEDS ATTENTION';
  if (score < 70) return 'DEVELOPING';
  return 'STRONG';
}

// Deterministic, real-data-grounded caption — see this file's top comment
// for why this is computed rather than pulled from narrative_md.
function scoreExplanation(score) {
  if (score < 40) {
    return 'This score reflects real gaps across technical SEO, content depth and AI-readiness — most of which are addressed by the recommendations on the following pages.';
  }
  if (score < 70) {
    return 'This score reflects a partially optimized site with specific, addressable gaps — the recommendations on the following pages close them.';
  }
  return 'This score reflects a well-optimized site. The recommendations on the following pages are refinements rather than fundamentals.';
}

