// "https://www.site.com/study-in-australia/" -> "site.com/study-in-australia"
export function prettyUrl(url, max = 58) {
  const s = String(url || '').replace(/^https?:\/\/(www\.)?/i, '').replace(/[?#].*$/, '').replace(/\/+$/, '');
  return s.length > max ? `${s.slice(0, max - 1)}…` : s;
}

// A real page from this client's own audit to anchor an example on.
