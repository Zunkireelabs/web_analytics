const MAX_ISSUES = 6;

// Real audit defects -> plain issues, grouped so the same plain title isn't
// listed twice. Falls back to the featured open recommendations when the
// crawl hadn't produced findings yet.
export function buildIssueList(issues) {
  const defects = issues.auditFindings?.topDefects || [];
  if (defects.length) {
    const byTitle = new Map();
    for (const d of defects) {
      const p = plainIssue(d.issue);
      const key = p.title;
      const existing = byTitle.get(key);
      if (existing) {
        existing.pages += d.pages;
        if (!existing.example && d.examplePages?.length) existing.example = d.examplePages[0];
      } else {
        byTitle.set(key, { ...p, pages: d.pages, example: (d.examplePages || [])[0] || null, high: d.priority === 'high' });
      }
    }
    return [...byTitle.values()].sort((a, b) => (b.high - a.high) || (b.pages - a.pages)).slice(0, MAX_ISSUES);
  }
  return selectFeaturedRecommendations(issues.openRecommendations?.items || [], MAX_ISSUES).map((item) => {
    const c = recommendationClientCopy(item);
    return { title: c.action, why: `Fixing this means ${c.benefit.replace(/^so /, '')}.`, routes: [], pages: null, example: item.page || null, auto: null };
  });
}

