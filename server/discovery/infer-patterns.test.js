import test from 'node:test';
import assert from 'node:assert/strict';
import { inferMappings } from './infer-patterns.js';

// Real tree shapes (2026-11-19): MOBILISE (Eleventy: src/<section>/<slug>/index.njk), Zennly (Eleventy: src/blog/<slug>.njk),
// SuperRank (Astro content collection: src/content/blog/<slug>.md).
const MOBILISE = ['src/index.njk', 'src/contact/index.njk', 'src/compare/index.njk', 'src/case-studies/index.njk', 'src/locations/index.njk',
  'src/blog/dark-social-attribution/index.njk', 'src/blog/death-of-curiosity-in-marketing/index.njk', 'src/blog/b2b-landing-page-best-practices/index.njk',
  'src/locations/bangalore/index.njk', 'src/locations/dubai/index.njk'];
const ZENNLY = ['src/blog.njk', 'src/blog/discount-leakage.njk', 'src/blog/gym-management-nepal.njk', 'src/blog/salon-booking-system-nepal.njk', 'src/solutions.njk', 'src/features/feature-pages.njk'];
const SUPERRANK = ['src/content/blog/aeo-for-local-businesses.md', 'src/content/blog/superrank-vs-athenahq.md', 'src/pages/blog/[slug].astro', 'src/pages/pricing.astro', 'src/pages/index.astro'];

test('MOBILISE: blog and locations each become ONE pattern, the section roots and the home page exact entries', () => {
  const r = inferMappings({ repoFiles: MOBILISE, unmappedPages: [
    'https://mobilise.agency/blog/dark-social-attribution/', 'https://mobilise.agency/blog/death-of-curiosity-in-marketing/', 'https://mobilise.agency/blog/b2b-landing-page-best-practices/',
    'https://mobilise.agency/locations/bangalore/', 'https://mobilise.agency/locations/dubai/',
    'https://mobilise.agency/', 'https://mobilise.agency/contact/', 'https://mobilise.agency/compare/', 'https://mobilise.agency/case-studies/', 'https://mobilise.agency/locations/'] });
  assert.deepEqual(r.patterns.map((p) => [p.match, p.file, p.covers]), [['^/blog/([^/]+)/?$', 'src/blog/$1/index.njk', 3], ['^/locations/([^/]+)/?$', 'src/locations/$1/index.njk', 2]]);
  assert.deepEqual(r.pages.map((p) => [p.path, p.file]).sort(), [['/', 'src/index.njk'], ['/case-studies', 'src/case-studies/index.njk'], ['/compare', 'src/compare/index.njk'], ['/contact', 'src/contact/index.njk'], ['/locations', 'src/locations/index.njk']]);
  assert.deepEqual(r.gaps, []);
});

test('Zennly: the blog is one pattern with the plain-file template; pages generated by a template (no file per page) are reported, not guessed', () => {
  const r = inferMappings({ repoFiles: ZENNLY, unmappedPages: ['https://zennly.io/blog/discount-leakage/', 'https://zennly.io/blog/gym-management-nepal/', 'https://zennly.io/blog/salon-booking-system-nepal/',
    'https://zennly.io/features/booking/', 'https://zennly.io/features/ai-assistant/', 'https://zennly.io/solutions/'] });
  assert.deepEqual(r.patterns.map((p) => [p.match, p.file]), [['^/blog/([^/]+)/?$', 'src/blog/$1.njk']]);
  assert.deepEqual(r.pages.map((p) => p.path), ['/solutions']);
  assert.deepEqual(r.gaps.map((g) => g.page).sort(), ['https://zennly.io/features/ai-assistant/', 'https://zennly.io/features/booking/']);
  assert.match(r.gaps[0].reason, /no-template-file/);
});

test('SuperRank (Astro): the blog resolves to the content collection, found under src/content, not the shared [slug].astro template', () => {
  const r = inferMappings({ repoFiles: SUPERRANK, unmappedPages: ['https://superrank.si/blog/aeo-for-local-businesses', 'https://superrank.si/blog/superrank-vs-athenahq', 'https://superrank.si/pricing', 'https://superrank.si/'] });
  assert.deepEqual(r.patterns.map((p) => [p.match, p.file]), [['^/blog/([^/]+)/?$', 'src/content/blog/$1.md']]);
  assert.deepEqual(r.pages.map((p) => [p.path, p.file]).sort(), [['/', 'src/pages/index.astro'], ['/pricing', 'src/pages/pricing.astro']]);
});

test('one missing file means NO pattern for that section: the pages that have files become exact entries, the rest are reported', () => {
  const r = inferMappings({ repoFiles: ZENNLY, unmappedPages: ['https://zennly.io/blog/discount-leakage/', 'https://zennly.io/blog/gym-management-nepal/', 'https://zennly.io/blog/not-a-file/'] });
  assert.deepEqual(r.patterns, []);
  assert.deepEqual(r.pages.map((p) => p.path).sort(), ['/blog/discount-leakage', '/blog/gym-management-nepal']);
  assert.match(r.gaps[0].reason, /the section's template exists for 2 of 3 pages/);
});

test('a page with several candidate files is reported as ambiguous, never picked', () => {
  const r = inferMappings({ repoFiles: ['src/about.njk', 'src/about/index.njk'], unmappedPages: ['https://x.com/about/'] });
  assert.deepEqual(r.pages, []);
  assert.match(r.gaps[0].reason, /ambiguous \(2 candidate files\)/);
});
